    private static (int Epoch, string Match, string Human, string Handle) FixtureSideSubscription;

    // Generated Playing is a native by-ref struct accessor, but its wrapper returns
    // ref *(ValueWithChangeNotify<bool>*)nativePointer as a managed object reference.
    // The generated field getter boxes the same native struct correctly. Read only;
    // playback writes still use the game's TogglePlayPause business method.
    internal static bool IsPlaying(MatchPlaybackController controller) => controller.m_isPlaying.Value;
    // A live109 failure surfaced only as ObjectCollectedException's message. Read each
    // known state member independently so the next live probe identifies the failing
    // member without retrying a business command or hiding an ambiguous controller.
    public static object DiagnoseControllers()
    {
        var rows = new List<object>();
        foreach (var obj in Resources.FindObjectsOfTypeAll(Il2CppType.Of<MatchPlaybackController>()))
        {
            if (rows.Count == 16) break;
            var values = new Dictionary<string, object>();
            void Read(string name, Func<object> read)
            {
                try { values[name] = new { ok = true, value = read() }; }
                catch (Exception error) { values[name] = new { ok = false, error = error.GetBaseException().ToString() }; }
            }
            MatchPlaybackController controller = null;
            Read("cast", () => { controller = obj.TryCast<MatchPlaybackController>(); return controller != null; });
            if (controller != null)
            {
                Read("pointer", () => controller.Pointer.ToInt64().ToString());
                Read("isActiveAndEnabled", () => controller.isActiveAndEnabled);
                Read("matchReference", () => controller.MatchReference?.GetPersistentIdentity());
                Read("playing", () => IsPlaying(controller));
                values["playingAccessor"] = "boxed m_isPlaying field; generated by-ref accessor is invalid";
                Read("pausedLocally", () => controller.IsPausedLocally);
                Read("pastMatch", () => controller.IsPastMatch);
                Read("replay", () => controller.IsPkmReplay);
                Read("finished", () => controller.IsFinished);
                Read("spectating", () => controller.IsSpectatingMatch);
                Read("multiplayer", () => controller.IsMultiplayerMatch);
                Read("kickedOff", () => controller.MatchKickedOff);
                Read("managerFixtureTeam", () => controller.CurrentManagerFixtureTeam.ToString());
                Read("matchHandle", () => controller.MatchHandle.m_handle.ToString());
                Read("matchInterface", () => controller.MatchInterface != null);
                Read("currentTimeSlice", () => controller.Match?.CurrentTimeSlice);
                Read("minute", () => controller.Match?.GetCurrentMinute());
                Read("continueState", () => controller.CurrentContinueButtonState.ToString());
                Read("phase", () => MatchPhase(controller));
            }
            rows.Add(values);
        }
        return new { ok = true, controllers = rows, sessionId = LiveTools.SessionId, epoch = LiveTools.CurrentEpoch,
            readOnly = true, scope = "member_level_controller_diagnostic_not_match_acceptance" };
    }

    private static MatchPlaybackController Controller(bool required)
    {
        var candidates = Resources.FindObjectsOfTypeAll(Il2CppType.Of<MatchPlaybackController>())
            .Select(obj => obj.TryCast<MatchPlaybackController>())
            .Where(controller => controller != null && controller.isActiveAndEnabled && controller.MatchReference != null).ToArray();
        if (candidates.Length == 0 && !required) return null;
        if (candidates.Length != 1) throw new InvalidOperationException("Expected exactly one active match playback controller.");
        return candidates[0];
    }

    internal static InteropReference CurrentReference() => Controller(true).MatchReference;
    internal static bool HasActivePlayback() => Controller(false) != null;

    private static void ClearFixtureSide()
    {
        var prior = FixtureSideSubscription;
        FixtureSideSubscription = default;
        if (prior.Handle != null && prior.Epoch == LiveTools.CurrentEpoch) LiveTools.Close(prior.Handle);
    }

    internal static FixtureTeam ManagerTeam(MatchPlaybackController controller)
    {
        if (controller.IsPastMatch || controller.IsPkmReplay || controller.IsSpectatingMatch) return FixtureTeam.Invalid;
        var reported = controller.CurrentManagerFixtureTeam;
        if (reported is FixtureTeam.Home or FixtureTeam.Away) return reported;
        var epoch = LiveTools.CurrentEpoch;
        var match = controller.MatchReference.GetPersistentIdentity();
        var human = LiveTools.GetReference("human").GetPersistentIdentity();
        var prior = FixtureSideSubscription;
        if (prior.Handle == null || prior.Epoch != epoch || prior.Match != match || prior.Human != human)
        {
            ClearFixtureSide();
            var subscription = LiveTools.Open("match", "", InternalCommands.PropertyId("MatchHumanFixtureTeam"), """{"human":{"source":"human"}}""");
            FixtureSideSubscription = (epoch, match, human, subscription.handle);
        }
        var side = LiveTools.GetSnapshot(FixtureSideSubscription.Handle);
        if (!side.Ready || side.Identity != match) return FixtureTeam.Invalid;
        return side.Value?.AsString() switch { "0" => FixtureTeam.Home, "1" => FixtureTeam.Away, _ => FixtureTeam.Invalid };
    }

    internal static MatchPlaybackController StageController(string managerSide)
    {
        var controller = Controller(true);
        if (controller.IsPastMatch || controller.IsPkmReplay || controller.IsSpectatingMatch)
            throw new InvalidOperationException("Current match does not belong to the active manager.");
        if (ManagerTeam(controller) != FixtureTeam.Invalid) return controller;
        var side = NegotiationActions.Channel(managerSide, "match", "MatchHumanFixtureTeam");
        var human = LiveTools.JsonText(LiveTools.DescribeValue(GameTools.MakeObjectTypedValue(LiveTools.GetReference("human"))));
        if (side.Identity != controller.MatchReference.GetPersistentIdentity() ||
            !side.ContextDescriptions.TryGetValue("human", out var owner) || owner != human ||
            side.Value?.AsString() is not ("0" or "1"))
            throw new InvalidOperationException("Native match data does not confirm the current manager's fixture team.");
        return controller;
    }

    internal sealed record PlayerContext(string MatchIdentity, bool IsHomeTeam, bool Playing, bool KickedOff, long? TimeSlice);
    internal static MatchPlaybackController ManagerController(bool requireUnfinished = true)
    {
        var controller = Controller(true);
        if (requireUnfinished) RequirePlayerMatch(controller);
        else if (ManagerTeam(controller) == FixtureTeam.Invalid)
            throw new InvalidOperationException("Current match does not belong to the active manager.");
        return controller;
    }
    internal static PlayerContext CapturePlayerContext(bool requireUnfinished = true)
    {
        var controller = ManagerController(requireUnfinished);
        return new PlayerContext(controller.MatchReference.GetPersistentIdentity(), ManagerTeam(controller) == FixtureTeam.Home,
            IsPlaying(controller), controller.MatchKickedOff, controller.Match == null ? null : Convert.ToInt64(controller.Match.CurrentTimeSlice));
    }

    private static void RequirePlayerMatch(MatchPlaybackController controller)
    {
        if (controller.IsPastMatch || controller.IsPkmReplay || controller.IsFinished || controller.IsSpectatingMatch)
            throw new InvalidOperationException("This is not an unfinished match managed by the active player.");
        if (ManagerTeam(controller) == FixtureTeam.Invalid)
            throw new InvalidOperationException("The active manager does not control a match team.");
    }

    public static object State(string operationId = "")
    {
        var controller = Controller(false);
        if (controller == null)
        {
            ClearFixtureSide();
            return new { ok = true, inMatch = false, epoch = LiveTools.CurrentEpoch, sessionId = LiveTools.SessionId };
        }
        var identity = controller.MatchReference.GetPersistentIdentity();
        var playing = IsPlaying(controller);
        if (!string.IsNullOrEmpty(operationId))
            return ActionCommands.ObserveDomain(operationId, identity, "match_playback", playing.ToString());
        var managerTeam = ManagerTeam(controller);
        return new { ok = true, inMatch = true, epoch = LiveTools.CurrentEpoch, sessionId = LiveTools.SessionId,
            mutationCursor = MutationActivity.Cursor,
            clientMutationGuardReady = MutationActivity.HooksReady,
            controllerIdentity = controller.Pointer.ToInt64().ToString(System.Globalization.CultureInfo.InvariantCulture),
            matchIdentity = identity, playing, pausedLocally = controller.IsPausedLocally, pastMatch = controller.IsPastMatch,
            replay = controller.IsPkmReplay, finished = controller.IsFinished, spectating = controller.IsSpectatingMatch,
            multiplayer = controller.IsMultiplayerMatch, kickedOff = controller.MatchKickedOff,
            isHomeTeam = managerTeam == FixtureTeam.Invalid ? (bool?)null : managerTeam == FixtureTeam.Home,
            currentTimeSlice = controller.Match?.CurrentTimeSlice, minute = controller.Match?.GetCurrentMinute(),
            currentManagerTeam = managerTeam.ToString(), continueState = controller.CurrentContinueButtonState.ToString(),
            phase = MatchPhase(controller) };
    }

    private static object MatchPhase(MatchPlaybackController controller)
    {
        try
        {
            var machine = controller.StateMachine; var state = machine?.CurrentState;
            if (state?.Scripts == null || state.CurrentStateMachine?.Pointer != machine.Pointer) return new { ready = false };
            var scripts = new List<object>();
            foreach (var script in state.Scripts)
            {
                var playback = script.TryCast<MatchPlaybackFSMState>();
                if (playback == null) continue;
                var flags = BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic;
                var status = typeof(MatchPlaybackFSMState).GetProperty("m_status", flags)?.GetValue(playback);
                var talk = script.TryCast<TeamTalkState>();
                scripts.Add(new { type = script.GetIl2CppType().FullName, belongsToCurrentMatch = playback.Controller?.Pointer == controller.Pointer && playback.State?.Pointer == state.Pointer,
                    continuationStatus = status?.ToString(), displayedPeriod = playback.DisplayedStateMatchPeriod.ToString(),
                    talkType = talk == null ? null : typeof(TeamTalkState).GetProperty("m_type", flags)?.GetValue(talk)?.ToString() });
            }
            return new { ready = true, stateGuid = state.GUID.ToString(), scripts, periodTransitionPreparing = controller.PeriodTransition?.IsPreparing,
                verificationScope = "managed_playback_phase_not_native_period_acceptance", silentAdvanceImplemented = false };
        }
        catch (Exception error) { return new { ready = false, error = error.GetBaseException().Message }; }
    }

    internal static FMMatchUIComponent Controls(MatchPlaybackController controller)
    {
        var property = typeof(MatchComponent).GetProperty("m_controller", BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic)
            ?? throw new InvalidOperationException("Match controller accessor is unavailable in this build.");
        var matches = Resources.FindObjectsOfTypeAll(Il2CppType.Of<FMMatchUIComponent>()).Select(obj => obj.TryCast<FMMatchUIComponent>())
            .Where(component => component != null && component.IsInitialised &&
                (property.GetValue(component) as MatchPlaybackController)?.Pointer == controller.Pointer).ToArray();
        if (matches.Length != 1) throw new InvalidOperationException("Match playback controls are not ready.");
        return matches[0];
    }

    internal static InteropReference RequireCurrentTactic(string source, bool allowFinished = false) =>
        RequireCurrentTactic(source, ManagerController(!allowFinished));

    internal static InteropReference RequireCurrentTactic(string source, MatchPlaybackController controller)
    {
        var target = LiveTools.GetReference(source);
        if (target.GetIl2CppType().FullName != "FM.UI.MatchTacticReference") throw new ArgumentException("A MatchTacticReference is required.");
        var component = Controls(controller);
        var identity = target.GetPersistentIdentity();
        foreach (var field in new[] { "m_tacticReference", "m_sessionTacticReference" })
        {
            var reference = typeof(FMMatchUIComponent).GetProperty(field, BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic)?.GetValue(component) as InteropReference;
            if (reference?.GetPersistentIdentity() == identity) return target;
        }
        throw new InvalidOperationException("This tactic does not belong to the active player's current match session.");
    }

    public static object SetPlaying(string id, bool playing, bool expected, long cursor = -1,
        string matchIdentity = "", string sessionId = "", int epoch = -1)
    {
        var controller = Controller(true);
        RequirePlayerMatch(controller);
        var identity = controller.MatchReference.GetPersistentIdentity();
        if ((!string.IsNullOrEmpty(matchIdentity) || !string.IsNullOrEmpty(sessionId) || epoch >= 0) &&
            (matchIdentity != identity || sessionId != LiveTools.SessionId || epoch != LiveTools.CurrentEpoch))
            throw new InvalidOperationException("Match or game session changed before the playback command.");
        var before = IsPlaying(controller);
        if (before != expected) throw new InvalidOperationException("Match playback state changed; read it again before applying.");
        MutationActivity.RequireUnchanged(cursor);
        var component = Controls(controller);
        var method = typeof(FMMatchUIComponent).GetMethod("TogglePlayPause", BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic)
            ?? throw new InvalidOperationException("Native match playback operation is unavailable.");
        return ActionCommands.DispatchDomain(id, "set_match_playing", identity, LiveTools.JsonText(new { playing, expected }),
            // Normal playback method. Resuming can close FM's own pause panel.
            // Calling it with fromTactics=false leaves the tactics-panel workflow alone.
            () => method.Invoke(component, new object[] { playing, false }), before.ToString(), playing.ToString(), "match_playback");
    }

    private static LiveTools.Snapshot Channel(string handle, string tactic, string property)
    {
        var snapshot = LiveTools.GetSnapshot(handle);
        if (!snapshot.Ready || snapshot.Identity != LiveTools.GetReference(tactic).GetPersistentIdentity() ||
            snapshot.Property != InternalCommands.PropertyId(property)) throw new ArgumentException("Wrong match tactic subscription: " + property);
        return snapshot;
    }

    public static object ChangeDraft(string id, string action, string tactic, string pending, string valid, bool expected, long cursor = -1)
    {
        var target = RequireCurrentTactic(tactic);
        var state = Channel(pending, tactic, "CanRevert");
        if (!bool.TryParse(state.Value?.AsString(), out var hasChanges) || hasChanges != expected)
            throw new InvalidOperationException("Match tactic draft changed; refresh before applying.");
        if (action != "confirm" && action != "cancel") throw new ArgumentException("Match draft action must be confirm or cancel.");
        MutationActivity.RequireUnchanged(cursor);
        if (action == "confirm")
        {
            var selection = Channel(valid, tactic, "IsTeamSelectionValid");
            if (!bool.TryParse(selection.Value?.AsString(), out var isValid) || !isValid)
                throw new InvalidOperationException("Game does not consider the current team selection valid.");
        }
        var eventId = action == "confirm" ? InteropEventIDs.EventFmxConfirmTacticalChanges : InteropEventIDs.EventFmxCancelTacticalChanges;
        var identity = target.GetPersistentIdentity();
        return ActionCommands.DispatchDomain(id, "match_draft_" + action, identity, LiveTools.JsonText(new { action, expected }),
            () => SI.Core.GameSubsystems.Get<GameInteropSubsystem>().SendEvent((uint)eventId, target, TypedValue.Create(true)),
            hasChanges.ToString(), "False", "match_tactical_draft." + action);
    }

    public static object ObserveDraft(string id, string action, string tactic, string pending)
    {
        var snapshot = Channel(pending, tactic, "CanRevert");
        return ActionCommands.ObserveDomain(id, LiveTools.GetReference(tactic).GetPersistentIdentity(), "match_tactical_draft." + action, snapshot.Value.AsString());
    }

    public static object BeginDraft(string id, string tactic, long cursor = -1, string data = "")
    {
        var target = RequireCurrentTactic(tactic);
        MutationActivity.RequireUnchanged(cursor);
        // Diagnostic parameter: the shipped event was tried with no data; "true"/"false"
        // let a live match test check whether the handler expects an explicit boolean.
        TypedValue payload = null;
        if (!string.IsNullOrEmpty(data))
        {
            if (!bool.TryParse(data, out var flag)) throw new ArgumentException("begin-draft data must be true, false or empty.");
            payload = TypedValue.Create(flag);
        }
        return ActionCommands.DispatchDomain(id, "begin_match_changes", target.GetPersistentIdentity(), "begin",
            () => SI.Core.GameSubsystems.Get<GameInteropSubsystem>().SendEvent((uint)InteropEventIDs.EventFmxMakingTacticalChanges, target, payload),
            null, null, "dispatch_history_only");
    }

    public static object Activity(long cursor, string owner) => new { ok = true, observation = MutationActivity.Observe(cursor, owner),
        hooksReady = MutationActivity.HooksReady, scope = "observed_managed_gameinterop_client_writes_only", nativeTransactionLock = false,
        sessionId = LiveTools.SessionId, epoch = LiveTools.CurrentEpoch };

    public static object PersonKey(string source, string path)
    {
        var person = LiveTools.GetReference(source, path).TryCast<FM.UI.PersonReference>()
            ?? throw new ArgumentException("A real person reference is required.");
        var record = person.TryCast<FM.UI.DatabaseRecordReference>() ?? throw new ArgumentException("Person has no native database identity.");
        return new { ok = true, databaseIndex = record.m_index, reference = person.GetPersistentIdentity(), epoch = LiveTools.CurrentEpoch, sessionId = LiveTools.SessionId };
    }
}
